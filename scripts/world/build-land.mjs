/**
 * Builds src/lib/worldLand.ts: the world's land as one SVG path, for the map
 * in the travel desk. Source: Natural Earth 1:110m land (public domain), via
 * the world-atlas package (ISC). Projection: plain equirectangular, x = lon +
 * 180, y = 90 - lat, so the map is 360 x 180 units and a city's lat/lon
 * places it directly. Run: node scripts/world/build-land.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../../node_modules/world-atlas/land-110m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);
const r = (n) => Math.round(n * 10) / 10;
let d = '';
const ring = (pts) => {
  let last = '';
  pts.forEach(([lon, lat], i) => {
    const p = `${r(lon + 180)} ${r(90 - lat)}`;
    if (p === last) return;
    d += (i === 0 ? 'M' : 'L') + p;
    last = p;
  });
  d += 'Z';
};
const geoms = land.type === 'FeatureCollection' ? land.features.map((f) => f.geometry) : [land.geometry];
for (const g of geoms) {
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const rg of poly) ring(rg);
}
writeFileSync(
  new URL('../../src/lib/worldLand.ts', import.meta.url),
  `/**\n * The world's land as one SVG path in a 360 x 180 equirectangular frame (x = lon + 180, y = 90 - lat).\n * Natural Earth 1:110m land, public domain, via world-atlas (ISC). Generated by scripts/world/build-land.mjs.\n */\nexport const WORLD_LAND_PATH =\n  '${d}';\n`,
);
console.log('path length', d.length);
